/// Lingua di Whisper per la lezione: «en» per gli insegnamenti in inglese
/// (lingua dell'esame o del riconoscitore, es. «en», «en-US»), altrimenti
/// «it». Mai il rilevamento automatico.
String lectureLanguage(String? language) {
  final l = (language ?? '').trim().toLowerCase();
  return l.startsWith('en') ? 'en' : 'it';
}

